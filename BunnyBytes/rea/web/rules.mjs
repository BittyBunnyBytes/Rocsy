const toRule = ([pattern, why]) => ({ pattern, why });
const clean = (list) => (Array.isArray(list) ? list : []).slice(0, 80)
  .map((r) => ({ pattern: String(r?.pattern || "").trim().slice(0, 200), why: String(r?.why || "").trim().slice(0, 400) }))
  .filter((r) => r.pattern);

function readOverrides() {
  try { return JSON.parse(fs.readFileSync(FILE, "utf8")); } catch { return {}; }
}

export function rulesFor(engine) {
  const id = DEFAULTS[engine] ? engine : "generic";
  const d = DEFAULTS[id], o = readOverrides()[id];
  return { id, label: d.label, custom: Boolean(o),
    focus: o ? clean(o.focus) : d.focus.map(toRule), skip: o ? clean(o.skip) : d.skip.map(toRule),
    notes: o ? String(o.notes || "") : d.notes };
}

// "Assembly-CSharp*.dll" matches a file name anywhere; a pattern with "/" matches the end of the
// relative path ("BepInEx/interop/X.dll"); "**" spans folders. Descriptions ("autoload scripts ...")
// are rules for the agent only and match nothing.
function globRe(pattern) {
  if (/\s/.test(pattern)) return null;
  const body = pattern.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*\*\/?/g, "\u0000").replace(/\*/g, "[^/]*")
    .replace(/\?/g, "[^/]").replace(/\u0000/g, ".*");
  return new RegExp(`(^|/)${body}$`, "i");
}
export function matchesRule(rule, rel) {
  const re = globRe(rule.pattern);
  return Boolean(re && re.test(rel.replace(/\\/g, "/")));
}

// Which assemblies the automatic ILSpy step decompiles: the hot files when any are present,
// otherwise everything not on the skip list.
export function pickAssemblies(engine, dlls) {
  const r = rulesFor(engine);
  const hot = dlls.filter((d) => r.focus.some((x) => matchesRule(x, d)));
  return hot.length ? hot : dlls.filter((d) => !r.skip.some((x) => matchesRule(x, d)));
}

// The block every mod brief carries (next to ENGINE VERSION).
export function rulesBrief(engine) {
  const r = rulesFor(engine), all = rulesFor("all");
  const line = (x) => `- ${x.pattern}${x.why ? ` — ${x.why}` : ""}`;
  const general = [...all.focus, ...all.skip].map(line).join("\n");
  if (!r.focus.length && !r.skip.length && !r.notes && !all.notes && !general) return "";
  return `MODDING RULES for ${r.label} (the user's Rules tab; they override your own habits):\n` +
    (all.notes ? `${all.notes}\n` : "") + (general ? `${general}\n` : "") +
    (r.focus.length ? `HOT FILES: the game's own code is here. Read, decompile, patch and hook these first and almost only these:\n${r.focus.map(line).join("\n")}\n` : "") +
    (r.skip.length ? `LEAVE ALONE: don't decompile, patch, transpile or debug these unless the user asked you to, or a hot-file type calls into them and you only need to read their API; ` +
      `errors from them that the unmodified game also logs are noise:\n${r.skip.map(line).join("\n")}\n` : "") +
    (r.notes ? `${r.notes}\n` : "");
}

async function gameFiles(dir, base = dir, depth = 0, out = []) {
  if (depth > 5 || out.length > 20000) return out;
  for (const e of await fsp.readdir(dir, { withFileTypes: true }).catch(() => [])) {
    if (e.isSymbolicLink()) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) await gameFiles(full, base, depth + 1, out);
    else out.push(path.relative(base, full));
  }
  return out;
}

// Routes under /REA/api/rules. `detectGame` comes from mods.mjs (passed in to keep imports one-way).
export async function handleRules({ method, api, url, req, res, send, readJson, httpError, targets, detectGame }) {
  if (api === "/rules" && method === "GET") {
    send(res, 200, { engines: Object.keys(DEFAULTS).map(rulesFor) });
    return true;
  }
  if (api === "/rules/for" && method === "GET") {
    const folder = targets[url.searchParams.get("folder")];
    if (!folder || folder.type !== "folder") throw httpError(404, "Unknown folder");
    const detected = await detectGame(folder.path);
    const files = await gameFiles(folder.path);
    const r = rulesFor(detected.engine);
    const hits = (list) => list.map((x) => ({ ...x, files: files.filter((f) => matchesRule(x, f)).slice(0, 20) }));
    send(res, 200, { engine: r.id, label: detected.label, rules: { ...r, focus: hits(r.focus), skip: hits(r.skip) } });
    return true;
  }
  const m = api.match(/^\/rules\/([a-z0-9-]+)$/);
  if (!m || !DEFAULTS[m[1]] || !["PUT", "DELETE"].includes(method)) return false;
  const all = readOverrides();
  if (method === "PUT") {
    const body = await readJson(req);
    all[m[1]] = { focus: clean(body.focus), skip: clean(body.skip), notes: String(body.notes || "").slice(0, 4000) };
  } else delete all[m[1]];
  await fsp.mkdir(DATA, { recursive: true });
  await fsp.writeFile(FILE + ".tmp", JSON.stringify(all, null, 1));
  await fsp.rename(FILE + ".tmp", FILE);
  send(res, 200, rulesFor(m[1]));
  return true;
}
